CREATE TABLE RP_EXPEDIENTES_COMEDOR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORGANIZACION_ID NUMBER NOT NULL,
    ESTADO_VALIDACION VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_ENVIO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RP_EXP_ORG
        FOREIGN KEY (ORGANIZACION_ID) REFERENCES ORGANIZACIONES(ID)
);

CREATE INDEX IX_RP_EXP_ORG
    ON RP_EXPEDIENTES_COMEDOR (ORGANIZACION_ID);

CREATE TABLE RP_DOCUMENTOS_COMEDOR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EXPEDIENTE_ID NUMBER NOT NULL,
    TIPO_DOCUMENTO VARCHAR2(40) DEFAULT 'ACREDITACION' NOT NULL,
    NOMBRE_ARCHIVO VARCHAR2(240) NOT NULL,
    TIPO_MIME VARCHAR2(100) NOT NULL,
    TAMANO_BYTES NUMBER(12) NOT NULL,
    CONTENIDO BLOB NOT NULL,
    HASH_SHA256 VARCHAR2(64) NOT NULL,
    ESTADO_OCR VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_CARGA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RP_DOC_EXP
        FOREIGN KEY (EXPEDIENTE_ID) REFERENCES RP_EXPEDIENTES_COMEDOR(ID)
);

CREATE INDEX IX_RP_DOC_EXP
    ON RP_DOCUMENTOS_COMEDOR (EXPEDIENTE_ID);

CREATE TABLE RP_RESULTADOS_OCR (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENTO_ID NUMBER NOT NULL,
    TEXTO_EXTRAIDO CLOB,
    NOMBRE_ORGANIZACION VARCHAR2(160),
    RUC_EXTRAIDO VARCHAR2(30),
    REPRESENTANTE VARCHAR2(160),
    CI_REPRESENTANTE VARCHAR2(30),
    CONFIANZA_OCR NUMBER(5,2),
    COINCIDE_RUC CHAR(1),
    COINCIDE_CI CHAR(1),
    RESULTADO_VALIDACION VARCHAR2(30),
    DETALLE_VALIDACION VARCHAR2(1000),
    PROCESADO_EN TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RP_RESULTADO_DOC UNIQUE (DOCUMENTO_ID),
    CONSTRAINT FK_RP_RES_DOC
        FOREIGN KEY (DOCUMENTO_ID) REFERENCES RP_DOCUMENTOS_COMEDOR(ID)
);

