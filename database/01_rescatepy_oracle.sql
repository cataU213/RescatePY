-- =========================================================
-- RESCATEPY - BASE DE DATOS ORACLE
-- Ejecutar conectado con el esquema/usuario RESCATEPY.
-- Oracle 12c o superior.
-- =========================================================

-- ---------------------------------------------------------
-- USUARIOS
-- ---------------------------------------------------------
CREATE TABLE usuarios (
    id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR2(120)
        NOT NULL,

    email VARCHAR2(180)
        NOT NULL,

    password_hash VARCHAR2(255)
        NOT NULL,

    creado_en TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT uq_usuarios_email
        UNIQUE (email)
);


-- ---------------------------------------------------------
-- DONACIONES
-- ---------------------------------------------------------
CREATE TABLE donaciones (
    id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    usuario_id NUMBER
        NOT NULL,

    donor_type VARCHAR2(80)
        NOT NULL,

    donor_name VARCHAR2(180)
        NOT NULL,

    food VARCHAR2(180)
        NOT NULL,

    quantity NUMBER(12,2)
        NOT NULL,

    unit VARCHAR2(40)
        NOT NULL,

    city VARCHAR2(120)
        NOT NULL,

    address VARCHAR2(300)
        NOT NULL,

    food_type VARCHAR2(100),

    food_condition VARCHAR2(120),

    hygiene VARCHAR2(120),

    requires_cold NUMBER(1)
        DEFAULT 0
        NOT NULL,

    cold_chain VARCHAR2(200),

    expiry_date VARCHAR2(30),

    prepared_storage VARCHAR2(200),

    notes VARCHAR2(1000),

    status VARCHAR2(30)
        DEFAULT 'ACTIVA'
        NOT NULL,

    receiver_type VARCHAR2(100),

    receiver_name VARCHAR2(180),

    receiver_responsible VARCHAR2(180),

    receiver_city VARCHAR2(120),

    published_at TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    updated_at TIMESTAMP WITH TIME ZONE,

    reserved_at TIMESTAMP WITH TIME ZONE,

    withdrawn_at TIMESTAMP WITH TIME ZONE,

    cancelled_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_donaciones_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id),

    CONSTRAINT ck_donaciones_cold
        CHECK (requires_cold IN (0, 1)),

    CONSTRAINT ck_donaciones_status
        CHECK (
            status IN (
                'ACTIVA',
                'RESERVADA',
                'RETIRADA',
                'CANCELADA'
            )
        )
);


-- ---------------------------------------------------------
-- RESERVAS
-- ---------------------------------------------------------
CREATE TABLE reservas (
    id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    donacion_id NUMBER
        NOT NULL,

    usuario_solicitante_id NUMBER
        NOT NULL,

    receiver_type VARCHAR2(100)
        NOT NULL,

    receiver_name VARCHAR2(180)
        NOT NULL,

    receiver_responsible VARCHAR2(180)
        NOT NULL,

    receiver_city VARCHAR2(120)
        NOT NULL,

    estado VARCHAR2(30)
        DEFAULT 'PENDIENTE'
        NOT NULL,

    creado_en TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT fk_reservas_donacion
        FOREIGN KEY (donacion_id)
        REFERENCES donaciones(id),

    CONSTRAINT fk_reservas_usuario
        FOREIGN KEY (usuario_solicitante_id)
        REFERENCES usuarios(id),

    CONSTRAINT ck_reservas_estado
        CHECK (
            estado IN (
                'PENDIENTE',
                'RETIRADA',
                'CANCELADA'
            )
        )
);


-- ---------------------------------------------------------
-- NOTIFICACIONES
-- ---------------------------------------------------------
CREATE TABLE notificaciones (
    id NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    usuario_id NUMBER
        NOT NULL,

    reserva_id NUMBER,

    mensaje VARCHAR2(1000)
        NOT NULL,

    leida NUMBER(1)
        DEFAULT 0
        NOT NULL,

    creado_en TIMESTAMP WITH TIME ZONE
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    CONSTRAINT fk_notificaciones_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id),

    CONSTRAINT fk_notificaciones_reserva
        FOREIGN KEY (reserva_id)
        REFERENCES reservas(id),

    CONSTRAINT ck_notificaciones_leida
        CHECK (leida IN (0, 1))
);


-- ---------------------------------------------------------
-- ÍNDICES
-- ---------------------------------------------------------
CREATE INDEX idx_donaciones_usuario
    ON donaciones(usuario_id);

CREATE INDEX idx_donaciones_status
    ON donaciones(status);

CREATE INDEX idx_reservas_donacion
    ON reservas(donacion_id);

CREATE INDEX idx_reservas_usuario
    ON reservas(usuario_solicitante_id);

CREATE INDEX idx_notificaciones_usuario
    ON notificaciones(usuario_id);

COMMIT;
