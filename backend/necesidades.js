"use strict";
const UNIDADES = new Set(["kg", "g", "litros", "unidades", "cajas", "bolsas", "paquetes", "raciones"]);
function validarNecesidad(body = {}) {
    // Los datos institucionales se toman de Oracle, no del formulario.
    const alimento = typeof body.alimento === "string" ? body.alimento.trim() : "";
    const unidad = typeof body.unidad === "string" ? body.unidad.trim().toLowerCase() : "";
    const cantidad = typeof body.cantidad === "number" ? body.cantidad : NaN;
    const detalle = typeof body.detalle === "string" ? body.detalle.trim() : "";
    if (!alimento || alimento.length > 150 || !UNIDADES.has(unidad) || !Number.isFinite(cantidad) || cantidad <= 0 || cantidad > 999999999 || Math.abs(cantidad * 1000 - Math.round(cantidad * 1000)) > 1e-6 || detalle.length > 500) {
        throw new Error("Ingresá alimento, cantidad positiva (hasta 3 decimales), unidad válida y detalle de hasta 500 caracteres.");
    }
    return { alimento, cantidad, unidad, detalle: detalle || null };
}
// Crea únicamente la tabla adicional; no modifica datos existentes.
async function asegurarTablaNecesidades(ejecutar) {
    await ejecutar(`BEGIN
      EXECUTE IMMEDIATE 'CREATE TABLE RP_NECESIDADES (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ORGANIZACION_ID NUMBER NOT NULL REFERENCES ORGANIZACIONES(ID),
        ALIMENTO VARCHAR2(150 CHAR) NOT NULL,
        CANTIDAD NUMBER(12,3) NOT NULL CHECK (CANTIDAD > 0),
        UNIDAD VARCHAR2(20 CHAR) NOT NULL,
        DETALLE VARCHAR2(500 CHAR),
        ESTADO VARCHAR2(10 CHAR) DEFAULT ''ACTIVA'' NOT NULL CHECK (ESTADO IN (''ACTIVA'', ''CERRADA'')),
        CREADO_EN TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CERRADO_EN TIMESTAMP WITH TIME ZONE
      )';
      EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
    END;`);
    await require("./seguimiento").asegurar(ejecutar,true);
}
function instalarRutasNecesidades(app, { autenticar, exigirOrganizacion, exigirDonante, obtenerTodos, ejecutar }) {
    const consulta = `SELECT n.ID, n.ALIMENTO, n.CANTIDAD, n.UNIDAD, n.DETALLE, n.ESTADO, n.CREADO_EN,
        o.NOMBRE_ORGANIZACION, o.DISTRITO FROM RP_NECESIDADES n JOIN ORGANIZACIONES o ON o.ID = n.ORGANIZACION_ID`;
    // Cada organización ve solo sus solicitudes.
    app.get("/api/comedor/necesidades", autenticar, exigirOrganizacion, async (req, res) => {
        try { res.json(await obtenerTodos(consulta + " WHERE n.ORGANIZACION_ID = :id AND n.ESTADO = 'ACTIVA' ORDER BY n.ID DESC", { id: req.organizacion.ID })); }
        catch (e) { console.error(e); res.status(500).json({ mensaje: "No se pudieron consultar las necesidades." }); }
    });
    app.post("/api/comedor/necesidades", autenticar, exigirOrganizacion, async (req, res) => {
        let datos;
        try { datos = validarNecesidad(req.body); } catch (e) { return res.status(400).json({ mensaje: e.message }); }
        try {
            await ejecutar(`INSERT INTO RP_NECESIDADES (ORGANIZACION_ID, ALIMENTO, CANTIDAD, UNIDAD, DETALLE) VALUES (:id, :alimento, :cantidad, :unidad, :detalle)`, { id: req.organizacion.ID, ...datos });
            res.status(201).json({ mensaje: "Necesidad publicada." });
        } catch (e) { console.error(e); res.status(500).json({ mensaje: "No se pudo publicar la necesidad." }); }
    });
    // Edición y eliminación limitadas a la organización propietaria.
    app.put("/api/comedor/necesidades/:id", autenticar, exigirOrganizacion, async (req, res) => {
        const id = Number(req.params.id);
        if (!Number.isSafeInteger(id) || id <= 0) return res.status(400).json({mensaje:"Identificador inválido."});
        let datos;
        try { datos=validarNecesidad(req.body); } catch(e) { return res.status(400).json({mensaje:e.message}); }
        try {
            const r=await ejecutar(`UPDATE RP_NECESIDADES SET ALIMENTO=:alimento,CANTIDAD=:cantidad,UNIDAD=:unidad,DETALLE=:detalle WHERE ID=:id AND ORGANIZACION_ID=:org AND ESTADO='ACTIVA'`,{...datos,id,org:req.organizacion.ID});
            if(r.rowsAffected!==1) return res.status(404).json({mensaje:"Necesidad activa no encontrada."});
            res.json({mensaje:"Necesidad actualizada."});
        } catch(e) { console.error(e); res.status(500).json({mensaje:"No se pudo actualizar la necesidad."}); }
    });
    app.delete("/api/comedor/necesidades/:id", autenticar, exigirOrganizacion, async (req,res)=>{
        const id=Number(req.params.id);
        if(!Number.isSafeInteger(id)||id<=0) return res.status(400).json({mensaje:"Identificador inválido."});
        try {
            // Baja lógica: conserva el historial pero desaparece de ambos listados.
            const r=await ejecutar(`UPDATE RP_NECESIDADES SET ESTADO='CERRADA',CERRADO_EN=SYSTIMESTAMP WHERE ID=:id AND ORGANIZACION_ID=:org AND ESTADO='ACTIVA'`,{id,org:req.organizacion.ID});
            if(r.rowsAffected!==1) return res.status(404).json({mensaje:"Necesidad activa no encontrada."});
            res.json({mensaje:"Necesidad eliminada."});
        } catch(e) { console.error(e);res.status(500).json({mensaje:"No se pudo eliminar la necesidad."}); }
    });
    // El donante solo consulta necesidades vigentes de organizaciones activas.
    app.get("/api/donante/necesidades", autenticar, exigirDonante, async (req, res) => {
        try { res.json(await obtenerTodos(consulta + " JOIN USUARIOS u ON u.ID = o.USUARIO_ID WHERE n.ESTADO = 'ACTIVA' AND o.ESTADO = 'ACTIVA' AND u.ESTADO_CUENTA = 'ACTIVA' AND u.TIPO_CUENTA = 'ORGANIZACION' ORDER BY n.ID DESC")); }
        catch (e) { console.error(e); res.status(500).json({ mensaje: "No se pudieron consultar las necesidades." }); }
    });
}
module.exports = { validarNecesidad, asegurarTablaNecesidades, instalarRutasNecesidades };
